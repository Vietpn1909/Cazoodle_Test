from datetime import date
from typing import Any

import pytest
from factories import raw_work
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.db.models import Author, Authorship, Meta, Work, WorkInstitution, WorkTopic
from pipeline.load_works import build_corpus, load_corpus

UIUC = "I157725225"


def _corpus(raws: list[dict[str, Any]], top_n: int = 10) -> Any:
    return build_corpus(
        raws,
        institution_id=UIUC,
        window_start=date(2024, 11, 16),
        window_end=date(2026, 11, 16),
        top_n=top_n,
    )


def test_build_corpus_reports_drops_and_cuts() -> None:
    raws = [
        raw_work(id="https://openalex.org/W1", doi="10.1/a"),
        raw_work(id="https://openalex.org/W1", doi="10.1/a"),  # same id twice
        raw_work(id="https://openalex.org/W2", doi="10.1/b", is_paratext=True),
        raw_work(id="https://openalex.org/W3", doi="10.1/a", cited_by_count=0),  # dup DOI
        raw_work(id="https://openalex.org/W4", doi="10.1/c", title="Other"),
        raw_work(id="https://openalex.org/W5", doi="10.1/d", title="Third"),
    ]
    corpus = _corpus(raws, top_n=2)
    r = corpus.report
    assert r["raw_records"] == 6
    assert r["dropped"]["duplicate_id"] == 1
    assert r["dropped"]["paratext"] == 1
    assert r["dropped"]["merged_versions"] == 1
    assert (r["eligible_after_filters"], r["selected"], r["cut_by_rank"]) == (3, 2, 1)
    scores = [w.work["rank_score"] for w in corpus.works]
    assert scores == sorted(scores, reverse=True)


@pytest.mark.db
def test_load_corpus_is_idempotent_and_prunes(db_session: Session) -> None:
    first = _corpus(
        [
            raw_work(id="https://openalex.org/W1", doi="10.1/a"),
            raw_work(id="https://openalex.org/W2", doi="10.1/b", title="Second"),
        ]
    )
    with db_session.begin():
        load_corpus(db_session, first.works, {"snapshot_date": "2026-11-16"})
    # simulate an embedding computed later; reload must keep it
    db_session.get(Work, "W1").embedding = [0.1] * 384  # type: ignore[union-attr]
    db_session.commit()

    second = _corpus([raw_work(id="https://openalex.org/W1", doi="10.1/a", cited_by_count=99)])
    with db_session.begin():
        load_corpus(db_session, second.works, {"snapshot_date": "2026-11-16"})

    def count(model: Any) -> int:
        return int(db_session.scalar(select(func.count()).select_from(model)) or 0)

    assert count(Work) == 1  # W2 pruned
    w1 = db_session.get(Work, "W1")
    assert w1 is not None and w1.cited_by_count == 99 and w1.embedding is not None
    assert count(Authorship) == 2 and count(Author) == 2
    assert count(WorkTopic) == 1 and count(WorkInstitution) == 3
    assert db_session.get(Meta, "snapshot_date").value == "2026-11-16"  # type: ignore[union-attr]
    # full-text vector generated by Postgres
    assert db_session.scalar(select(Work.tsv).where(Work.id == "W1"))
